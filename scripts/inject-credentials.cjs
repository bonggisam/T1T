#!/usr/bin/env node
/**
 * 빌드 타임 자격증명 주입.
 *
 * v2.4.1+ 동작:
 *   1. .env 파일 읽음
 *   2. dist/main/main.js 가 컴파일된 후, 그 안의 빈 문자열을 실제 값으로 교체
 *      (tsc 후 후처리)
 *
 * v2.3.x 호환:
 *   - src/main/credentials.gen.ts 도 함께 생성 (개발 모드 + 백업)
 */
const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');

const projectRoot = path.join(__dirname, '..');
const envPath = path.join(projectRoot, '.env');
const tsOutPath = path.join(projectRoot, 'src', 'main', 'credentials.gen.ts');
const jsOutPath = path.join(projectRoot, 'dist', 'main', 'credentials.gen.js');

let env = {};
if (fs.existsSync(envPath)) {
  env = dotenv.parse(fs.readFileSync(envPath, 'utf-8'));
  console.log('[InjectCredentials] Loaded .env');
} else {
  console.warn('[InjectCredentials] .env not found — credentials will be empty (Google 연동 비활성)');
}

const clientId = env.GOOGLE_CLIENT_ID || '';
const clientSecret = env.GOOGLE_CLIENT_SECRET || '';
const tpassPassword = env.TPASS_PASSWORD || '';
if (!tpassPassword) {
  console.warn('[InjectCredentials] TPASS_PASSWORD 미설정 — 외출시스템에서 비밀번호를 직접 넣어야 합니다');
}

// 렌더러용 주소는 Vite가 .env에서 직접 읽어 번들에 넣는다. 빠지면 해당 화면이 안내문만 표시하므로 미리 알린다.
for (const key of ['VITE_TPASS_URL', 'VITE_OUTING_URL', 'VITE_NEIS_KEY']) {
  if (!env[key] && !process.env[key]) {
    console.warn(`[InjectCredentials] ${key} 미설정 — 해당 화면은 주소 없음 안내만 표시합니다`);
  }
}

// TypeScript 소스 (tsc 입력)
const tsContent = `// AUTO-GENERATED by scripts/inject-credentials.cjs — DO NOT EDIT
// Built at: ${new Date().toISOString()}
export const GOOGLE_CLIENT_ID: string = ${JSON.stringify(clientId)};
export const GOOGLE_CLIENT_SECRET: string = ${JSON.stringify(clientSecret)};
export const TPASS_PASSWORD: string = ${JSON.stringify(tpassPassword)};
`;
fs.writeFileSync(tsOutPath, tsContent);
console.log(`[InjectCredentials] Wrote ${path.relative(projectRoot, tsOutPath)} (clientId ${clientId.length} chars)`);

// JS 출력도 직접 생성 (dist가 이미 있으면 tsc가 덮어쓰지만, 안전 보장)
if (fs.existsSync(path.dirname(jsOutPath))) {
  const jsContent = `"use strict";
Object.defineProperty(exports, "__esModule", { value: true });
exports.TPASS_PASSWORD = exports.GOOGLE_CLIENT_SECRET = exports.GOOGLE_CLIENT_ID = void 0;
// AUTO-GENERATED by scripts/inject-credentials.cjs
exports.GOOGLE_CLIENT_ID = ${JSON.stringify(clientId)};
exports.GOOGLE_CLIENT_SECRET = ${JSON.stringify(clientSecret)};
exports.TPASS_PASSWORD = ${JSON.stringify(tpassPassword)};
`;
  fs.writeFileSync(jsOutPath, jsContent);
  console.log(`[InjectCredentials] Also wrote ${path.relative(projectRoot, jsOutPath)}`);
}

// 추가 보호: dist/main/main.js 가 이미 존재하면 인라인 교체
const mainJsPath = path.join(projectRoot, 'dist', 'main', 'main.js');
if (fs.existsSync(mainJsPath)) {
  let mainJs = fs.readFileSync(mainJsPath, 'utf-8');
  const before = mainJs.length;
  // credentials_gen_1.GOOGLE_CLIENT_ID 사용처 직접 인라인 (안전 백업)
  mainJs = mainJs.replace(/credentials_gen_1\.GOOGLE_CLIENT_ID/g, JSON.stringify(clientId));
  mainJs = mainJs.replace(/credentials_gen_1\.GOOGLE_CLIENT_SECRET/g, JSON.stringify(clientSecret));
  mainJs = mainJs.replace(/credentials_gen_1\.TPASS_PASSWORD/g, JSON.stringify(tpassPassword));
  if (mainJs.length !== before) {
    fs.writeFileSync(mainJsPath, mainJs);
    console.log(`[InjectCredentials] Inlined credentials into ${path.relative(projectRoot, mainJsPath)}`);
  }
}
